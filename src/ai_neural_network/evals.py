def grade(task: dict[str, str], text: str) -> bool:
    kind, want = task["kind"], task["answer"]
    if kind == "json":  # the JSON may come before the ANSWER line, on it, or be the whole reply
        for part in (text.rsplit("ANSWER:", 1)[-1], text.split("ANSWER:")[0], text):
            try:
                if _parse_json(part) == json.loads(want):
                    return True
            except ValueError:
                continue
        return False
    got = _final(text)
    if kind == "number":
        return re.sub(r"[^0-9-]", "", got.split("=")[-1]) == want
    if kind == "regex":
        return re.fullmatch(want, got.removeprefix("answer:").strip()) is not None
    return got == " ".join(want.lower().split())


def run_tier(reg: Registry, tier: str, tasks: list[dict[str, str]], timeout_s: float) -> dict[str, Any]:
    ok, times, misses, errors_in_row = 0, [], [], 0
    for t in tasks:
        if errors_in_row >= 3:  # provider down or out of quota: score the rest as misses, don't wait on each
            misses.append(f"{t['id']}: skipped after 3 errors in a row")
            continue
        start = time.monotonic()
        try:  # the tier alone: no fallback, no cooldown gate (a cooldown from one slow task would fail the rest)
            r = _ask_one(reg, tier, t["prompt"], system=SYSTEM, max_tokens=16000, timeout_s=timeout_s)
            hit, errors_in_row = grade(t, r.text), 0
            if not hit:
                misses.append(f"{t['id']}: {_final(r.text)[:30]!r}")
        except FleetError as e:
            hit, errors_in_row = False, errors_in_row + 1
            misses.append(f"{t['id']}: ERR {str(e)[:50]}")
        ok += hit
        times.append(time.monotonic() - start)
    return {"ts": iso(now()), "tier": tier, "model": reg.tiers[tier].model, "score": ok, "n": len(tasks),
            "median_s": round(statistics.median(times), 1) if times else None, "misses": misses}


def evaluate(reg: Registry, tiers: list[str], only: list[str] | None = None, timeout_s: float = 180) -> list[dict[str, Any]]:
    """Run the task set on each tier; tiers on one provider run one after another, providers in parallel."""
    unknown = [t for t in tiers if t not in reg.tiers]
    if unknown:
        raise FleetError(f"unknown tier {unknown[0]!r}")
    tasks = [t for t in TASKS if not only or t["id"] in only]
    groups: dict[str, list[str]] = {}
    for t in tiers:
        groups.setdefault(reg.tiers[t].base_url, []).append(t)
    with ThreadPoolExecutor(len(groups)) as ex:
        rows = [r for rs in ex.map(lambda g: [run_tier(reg, t, tasks, timeout_s) for t in g], groups.values()) for r in rs]
    path = state_dir() / "evals.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    return sorted(rows, key=lambda r: (-r["score"], r["median_s"] or 1e9))


def apply_scores(net, rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Feed bake-off scores back into the synapses (the eval -> learning loop).

    Each scored tier's incoming excitatory edges move by 0.05 * (2*frac - 1):
    a perfect score strengthens every pathway into that neuron, a zero weakens
    them, a half score leaves them alone. Returns the changed edges.
    """
    changed = []
    for r in rows:
        tier, n = r.get("tier"), r.get("n") or 0
        if not tier or not n or tier not in net.neurons:
            continue
        delta = 0.05 * (2 * (r["score"] / n) - 1)
        if not delta:
            continue
        for (a, b), w in list(net.synapses.items()):
            if b == tier and w > 0:
                net.synapses[(a, b)] = max(0.0, min(1.0, w + delta))
                changed.append({"edge": f"{a}->{b}", "tier": tier, "delta": round(delta, 4)})
    return changed
